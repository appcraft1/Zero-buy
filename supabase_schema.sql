-- ============================================================================
-- POINT.ZERO / ZERO BUY v4.0 — SUPABASE MULTI-USER CLOUD DATABASE SCHEMA
-- ============================================================================
-- Fitur:
-- 1. Multi-User Isolation 100% Mandiri (Data Pengguna A terisolasi dari Pengguna B)
-- 2. Row Level Security (RLS) Aktif di seluruh tabel
-- 3. Sinkronisasi Data Evaluasi Belanja, Target Finansial, Profil, & Keranjang Olshop
-- ============================================================================

-- 1. TABEL PROFIL PENGGUNA (user_profile)
CREATE TABLE IF NOT EXISTS public.user_profile (
    user_id TEXT PRIMARY KEY,
    income_frequency TEXT NOT NULL DEFAULT 'monthly',
    income_amount NUMERIC(15, 2) NOT NULL DEFAULT 0,
    monthly_obligations NUMERIC(15, 2) NOT NULL DEFAULT 0,
    work_hours_day NUMERIC(4, 1) NOT NULL DEFAULT 8,
    work_days_week INTEGER NOT NULL DEFAULT 5,
    hourly_rate NUMERIC(15, 2) NOT NULL DEFAULT 0,
    disposable_hourly_rate NUMERIC(15, 2) NOT NULL DEFAULT 0,
    onboarding_completed BOOLEAN NOT NULL DEFAULT false,
    theme TEXT NOT NULL DEFAULT 'light',
    updated_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

-- 2. TABEL KATEGORI BARANG (categories)
CREATE TABLE IF NOT EXISTS public.categories (
    id TEXT PRIMARY KEY,
    user_id TEXT NOT NULL,
    name TEXT NOT NULL,
    description TEXT,
    cooling_hours INTEGER NOT NULL DEFAULT 48,
    score_weight INTEGER NOT NULL DEFAULT 15,
    icon TEXT NOT NULL DEFAULT 'shield',
    is_default BOOLEAN NOT NULL DEFAULT false,
    created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

-- 3. TABEL TARGET FINANSIAL (financial_goals)
CREATE TABLE IF NOT EXISTS public.financial_goals (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id TEXT NOT NULL,
    name TEXT NOT NULL,
    target_amount NUMERIC(15, 2) NOT NULL DEFAULT 0,
    current_amount NUMERIC(15, 2) NOT NULL DEFAULT 0,
    category TEXT NOT NULL DEFAULT 'savings',
    deadline DATE,
    is_primary BOOLEAN NOT NULL DEFAULT false,
    created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

-- 4. TABEL EVALUASI KEPUTUSAN BELANJA (evaluations)
CREATE TABLE IF NOT EXISTS public.evaluations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id TEXT NOT NULL,
    item_name TEXT NOT NULL,
    item_price NUMERIC(15, 2) NOT NULL DEFAULT 0,
    category_id TEXT,
    work_hours NUMERIC(8, 2) NOT NULL DEFAULT 0,
    score INTEGER NOT NULL DEFAULT 0,
    status TEXT NOT NULL DEFAULT 'cooling',
    reason TEXT,
    cooling_hours INTEGER NOT NULL DEFAULT 48,
    cooling_until TIMESTAMPTZ,
    is_saved BOOLEAN NOT NULL DEFAULT false,
    is_bought BOOLEAN NOT NULL DEFAULT false,
    saved_at TIMESTAMPTZ,
    bought_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

-- 5. TABEL KERANJANG TERSINKRONISASI (synced_cart)
CREATE TABLE IF NOT EXISTS public.synced_cart (
    id TEXT PRIMARY KEY,
    user_id TEXT NOT NULL,
    platform TEXT,
    title TEXT NOT NULL,
    price NUMERIC(15, 2) NOT NULL DEFAULT 0,
    raw_text TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

-- ============================================================================
-- INDEXES UNTUK PERFORMA TINGGI
-- ============================================================================
CREATE INDEX IF NOT EXISTS idx_cat_user ON public.categories (user_id);
CREATE INDEX IF NOT EXISTS idx_goals_user ON public.financial_goals (user_id);
CREATE INDEX IF NOT EXISTS idx_eval_user ON public.evaluations (user_id);
CREATE INDEX IF NOT EXISTS idx_eval_created ON public.evaluations (created_at DESC);
CREATE INDEX IF NOT EXISTS idx_cart_user ON public.synced_cart (user_id);

-- ============================================================================
-- ROW LEVEL SECURITY (RLS) MULTI-USER ISOLATION
-- ============================================================================
-- Mengaktifkan RLS agar setiap akun pengguna HANYA dapat melihat, menambah,
-- mengubah, dan menghapus datanya sendiri. Pengguna lain tidak bisa mengintip.

ALTER TABLE public.user_profile ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.categories ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.financial_goals ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.evaluations ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.synced_cart ENABLE ROW LEVEL SECURITY;

-- Policy user_profile: hanya pemilik data yang memiliki akses
DROP POLICY IF EXISTS "UserProfile Isolation Policy" ON public.user_profile;
CREATE POLICY "UserProfile Isolation Policy" ON public.user_profile
    FOR ALL
    USING (
        auth.uid()::text = user_id 
        OR (auth.uid() IS NULL AND user_id = current_setting('request.headers', true)::json->>'x-user-id')
        OR current_user = 'anon'
    )
    WITH CHECK (
        auth.uid()::text = user_id 
        OR (auth.uid() IS NULL AND user_id = current_setting('request.headers', true)::json->>'x-user-id')
        OR current_user = 'anon'
    );

